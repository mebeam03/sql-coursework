-- Furniture replacement service requests
-- Corrected to display property address (not office address).
SELECT
    SR.PROPERTY_ID,
    P.OFFICE_NUM,
    P.ADDRESS AS PROPERTY_ADDRESS,
    SR.EST_HOURS,
    SR.SPENT_HOURS,
    O.OWNER_NUM,
    O.LAST_NAME AS OWNER_LAST_NAME
FROM SERVICE_REQUEST SR
INNER JOIN SERVICE_CATEGORY SC ON SR.CATEGORY_NUMBER = SC.CATEGORY_NUM
INNER JOIN PROPERTY P ON SR.PROPERTY_ID = P.PROPERTY_ID
INNER JOIN OWNER O ON P.OWNER_NUM = O.OWNER_NUM
WHERE SC.CATEGORY_DESCRIPTION = 'Furniture replacement';
