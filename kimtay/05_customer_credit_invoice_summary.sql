-- KimTay Pet Supplies | Invoices exceeding $250 from customers in good credit standing
-- Selected from uploaded class practice; presentation formatting only.
SELECT
    I.CUST_ID,
    I.INVOICE_NUM,
    I.INVOICE_DATE,
    SUM(IL.QUANTITY * IL.QUOTED_PRICE) AS INVOICE_TOTAL
FROM INVOICES I
INNER JOIN INVOICE_LINE IL ON I.INVOICE_NUM = IL.INVOICE_NUM
WHERE I.CUST_ID IN (
    SELECT CUST_ID
    FROM CUSTOMER
    WHERE CREDIT_LIMIT > BALANCE
)
GROUP BY I.CUST_ID, I.INVOICE_NUM, I.INVOICE_DATE
HAVING SUM(IL.QUANTITY * IL.QUOTED_PRICE) > 250
ORDER BY I.INVOICE_NUM ASC;
